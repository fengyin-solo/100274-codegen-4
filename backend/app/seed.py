from __future__ import annotations

from typing import Any


def _booking_row(
    row_id: int,
    booking_no: str,
    shipper: str | None,
    contact: str | None,
    phone: str | None,
    route: str,
    pol: str,
    pod: str,
    vessel_voyage: str,
    containers: str,
    cutoff_time: str,
    submitted_at: str,
    *,
    status: str = "待受理",
    space_released: bool = False,
    abnormal: bool = False,
) -> dict[str, Any]:
    """订舱样例行：保留托运人缺字段、舱位释放、同票重复提交等情形供受理列表过滤。"""
    return {
        "id": row_id,
        "status": status,
        "pending": status == "待受理",
        "abnormal": abnormal,
        "订舱号": booking_no,
        "托运人名称": shipper,
        "托运人联系人": contact,
        "托运人联系电话": phone,
        "航线": route,
        "起运港": pol,
        "目的港": pod,
        "船名航次": vessel_voyage,
        "箱型箱量": containers,
        "截关时间": cutoff_time,
        "提交时间": submitted_at,
        "舱位释放": space_released,
    }


